def normalize_location(loc: Optional[str]) -> str:
    """将 home_xxx 归一化为 home，None 返回空串"""
    if loc is None:
        return ""
    if loc.startswith("home_"):
        return "home"
    return loc


def player_owned_names(player) -> Set[str]:
    """返回玩家当前持有的所有武器和物品的名称集合。

    兼容 weapons/items 为对象列表或字符串列表两种情况。
    """
    names: Set[str] = set()
    for collection in (getattr(player, 'weapons', None),
                        getattr(player, 'items', None)):
        if collection is None:
            continue
        for obj in collection:
            if obj is None:
                continue
            names.add(obj.name if hasattr(obj, "name") else str(obj))
    return names
